export function getMotorById(id: string): Motor | undefined {
  return motors.find((m) => m.id === id);
}

export function getVehicleById(id: string): Vehicle | undefined {
  return vehicles.find((v) => v.id === id);
}

export function getVehiclesByMotor(motorId: string): Vehicle[] {
  return vehicles.filter((v) => v.motorId === motorId);
}

export function searchMotors(query: string): Motor[] {
  const q = query.toLowerCase().trim();
  if (!q) return motors;
  return motors.filter(
    (m) =>
      m.name.toLowerCase().includes(q) ||
      m.code.toLowerCase().includes(q) ||
      m.brands.some((b) => b.toLowerCase().includes(q)) ||
      m.fuel.toLowerCase().includes(q)
  );
}

export function searchVehicles(query: string): Vehicle[] {
  const q = query.toLowerCase().trim();
  if (!q) return vehicles;
  return vehicles.filter(
    (v) =>
      v.name.toLowerCase().includes(q) ||
      v.brand.toLowerCase().includes(q) ||
      v.engine.toLowerCase().includes(q) ||
      v.desc.toLowerCase().includes(q)
  );
}